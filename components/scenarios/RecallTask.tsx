'use client';

import { useEffect, useMemo, useRef, useState } from 'react';
import clsx from 'clsx';
import { clock } from '@/lib/simulation/clock';
import { PALETTE_HEX } from '@/lib/visualization/palette';

/**
 * The recall task.
 *
 * A scene is shown briefly, hidden, and then you answer questions about it. The
 * reconstruction classifies every element of the scene by how it came back:
 * strongly encoded, weakly encoded, inferred, or missing.
 *
 * The inference category is the important one. Two items in the scene are
 * *schema-consistent but absent* — a chair at a desk, a clock on a wall — and
 * the question set asks about them. People frequently report them. That is the
 * finding, generated by you rather than asserted at you.
 */

type Phase = 'ready' | 'study' | 'gap' | 'quiz' | 'reconstruct';

interface Item {
  id: string;
  label: string;
  x: number;
  y: number;
  w: number;
  h: number;
  /** Visually prominent items are more likely to be encoded strongly. */
  prominence: number;
  /** Present in the scene, or merely implied by it? */
  present: boolean;
}

const SCENE: Item[] = [
  { id: 'desk', label: 'Desk', x: 18, y: 54, w: 44, h: 22, prominence: 0.95, present: true },
  { id: 'lamp', label: 'Desk lamp', x: 24, y: 34, w: 12, h: 18, prominence: 0.8, present: true },
  { id: 'mug', label: 'Red mug', x: 48, y: 46, w: 8, h: 8, prominence: 0.65, present: true },
  { id: 'laptop', label: 'Laptop', x: 32, y: 42, w: 18, h: 12, prominence: 0.85, present: true },
  { id: 'poster', label: 'Poster', x: 70, y: 22, w: 18, h: 22, prominence: 0.5, present: true },
  { id: 'plant', label: 'Small plant', x: 88, y: 50, w: 9, h: 14, prominence: 0.3, present: true },
  { id: 'pen', label: 'Pen', x: 56, y: 52, w: 6, h: 3, prominence: 0.15, present: true },
  // Implied but absent — the schema traps.
  { id: 'chair', label: 'Chair', x: 36, y: 72, w: 16, h: 16, prominence: 0, present: false },
  { id: 'clock', label: 'Wall clock', x: 54, y: 16, w: 10, h: 10, prominence: 0, present: false },
];

const QUESTIONS = ['laptop', 'mug', 'chair', 'plant', 'clock', 'poster'];

const STUDY_MS = 4000;

const CATEGORY = {
  strong: { label: 'Strongly encoded', color: PALETTE_HEX.green },
  weak: { label: 'Weakly encoded', color: PALETTE_HEX.amber },
  inferred: { label: 'Inferred', color: PALETTE_HEX.threat },
  missing: { label: 'Missing', color: '#3a4152' },
} as const;

type Category = keyof typeof CATEGORY;

export function RecallTask() {
  const [phase, setPhase] = useState<Phase>('ready');
  const [answers, setAnswers] = useState<Record<string, boolean>>({});
  const [qIndex, setQIndex] = useState(0);
  const [elapsed, setElapsed] = useState(0);
  const timers = useRef<number[]>([]);

  useEffect(
    () => () => {
      timers.current.forEach(window.clearTimeout);
    },
    [],
  );

  const begin = () => {
    setAnswers({});
    setQIndex(0);
    setPhase('study');
    const start = Date.now();
    const tick = window.setInterval(() => {
      const t = Date.now() - start;
      setElapsed(t);
      if (t >= STUDY_MS) window.clearInterval(tick);
    }, 60);
    timers.current.push(
      window.setTimeout(() => setPhase('gap'), STUDY_MS),
      window.setTimeout(() => setPhase('quiz'), STUDY_MS + 900),
    );
  };

  const answer = (yes: boolean) => {
    const id = QUESTIONS[qIndex];
    setAnswers((prev) => ({ ...prev, [id]: yes }));
    if (qIndex + 1 >= QUESTIONS.length) {
      setPhase('reconstruct');
      clock.seek(0);
      clock.play();
    } else {
      setQIndex((i) => i + 1);
    }
  };

  /** Classify each scene element by how it came back. */
  const classified = useMemo((): Array<Item & { category: Category }> => {
    return SCENE.map((item) => {
      const said = answers[item.id];
      let category: Category;
      if (!item.present) {
        category = said === true ? 'inferred' : 'missing';
      } else if (said === true) {
        category = item.prominence >= 0.6 ? 'strong' : 'weak';
      } else if (said === false) {
        category = 'missing';
      } else {
        // Not asked about: classify from prominence alone.
        category = item.prominence >= 0.75 ? 'strong' : item.prominence >= 0.4 ? 'weak' : 'missing';
      }
      return { ...item, category };
    });
  }, [answers]);

  const falseMemories = classified.filter((c) => c.category === 'inferred');
  const currentQ = SCENE.find((s) => s.id === QUESTIONS[qIndex]);

  return (
    <div className="p-4">
      <div className="relative mb-3 h-[150px] overflow-hidden border border-white/[0.06] bg-void-900">
        {/* The scene, during study and during reconstruction. */}
        {(phase === 'study' || phase === 'reconstruct') && (
          <div className="absolute inset-0">
            {(phase === 'study' ? SCENE.filter((s) => s.present) : classified).map((item) => {
              const cat =
                'category' in item ? CATEGORY[(item as { category: Category }).category] : null;
              const isAbsent = !item.present;
              if (phase === 'study' && isAbsent) return null;
              return (
                <div
                  key={item.id}
                  className="absolute flex items-end justify-center transition-all duration-700"
                  style={{
                    left: `${item.x}%`,
                    top: `${item.y}%`,
                    width: `${item.w}%`,
                    height: `${item.h}%`,
                    background:
                      phase === 'study'
                        ? `rgba(242,237,228,${0.1 + item.prominence * 0.22})`
                        : `${cat?.color ?? '#333'}2e`,
                    border:
                      phase === 'study'
                        ? `1px solid rgba(242,237,228,${0.2 + item.prominence * 0.4})`
                        : `1px ${isAbsent ? 'dashed' : 'solid'} ${cat?.color ?? '#333'}`,
                  }}
                >
                  {phase === 'reconstruct' && (
                    <span
                      className="w-full truncate px-1 pb-0.5 text-center font-mono text-[7.5px] uppercase tracking-wider2"
                      style={{ color: cat?.color }}
                    >
                      {item.label}
                    </span>
                  )}
                </div>
              );
            })}

            {phase === 'study' && (
              <div className="absolute inset-x-0 bottom-0 h-[2px] bg-white/10">
                <div
                  className="h-full bg-signal-violet transition-[width]"
                  style={{ width: `${Math.min(100, (elapsed / STUDY_MS) * 100)}%` }}
                />
              </div>
            )}
          </div>
        )}

        {phase === 'ready' && (
          <div className="flex h-full items-center justify-center px-4 text-center">
            <div>
              <p className="font-display text-[18px] text-bone">Study the scene</p>
              <p className="mt-2 text-[11.5px] leading-snug text-bone-dim">
                You get four seconds. Then questions.
              </p>
            </div>
          </div>
        )}

        {phase === 'gap' && (
          <div className="flex h-full items-center justify-center">
            <p className="instrument">Hidden</p>
          </div>
        )}

        {phase === 'quiz' && currentQ && (
          <div className="flex h-full flex-col items-center justify-center px-4 text-center">
            <p className="instrument mb-2">
              Question {qIndex + 1} of {QUESTIONS.length}
            </p>
            <p className="font-display text-[19px] leading-tight text-bone">
              Was there a {currentQ.label.toLowerCase()}?
            </p>
            <div className="mt-4 flex gap-2">
              <button type="button" onClick={() => answer(true)} className="btn px-5">
                Yes
              </button>
              <button type="button" onClick={() => answer(false)} className="btn px-5">
                No
              </button>
            </div>
          </div>
        )}
      </div>

      {phase === 'reconstruct' ? (
        <>
          <div className="mb-3 grid grid-cols-2 gap-1.5">
            {(Object.keys(CATEGORY) as Category[]).map((k) => {
              const count = classified.filter((c) => c.category === k).length;
              return (
                <div key={k} className="flex items-center gap-1.5">
                  <span
                    className="h-2 w-2 shrink-0"
                    style={{ background: CATEGORY[k].color }}
                    aria-hidden
                  />
                  <span className="truncate font-mono text-[9px] uppercase tracking-wider2 text-bone-faint">
                    {CATEGORY[k].label}
                  </span>
                  <span className="ml-auto font-mono text-[9px] tabular-nums text-bone-dim">
                    {count}
                  </span>
                </div>
              );
            })}
          </div>

          <p className="text-[11.5px] leading-[1.6] text-bone-dim">
            {falseMemories.length > 0 ? (
              <>
                You reported{' '}
                <strong className="text-signal-threat">
                  {falseMemories.map((f) => f.label.toLowerCase()).join(' and ')}
                </strong>
                . {falseMemories.length === 1 ? 'It was' : 'They were'} never in the
                scene. {falseMemories.length === 1 ? 'It is' : 'They are'} exactly
                what a desk scene usually contains, so pattern completion supplied{' '}
                {falseMemories.length === 1 ? 'it' : 'them'} — and nothing marked{' '}
                {falseMemories.length === 1 ? 'it' : 'them'} as supplied.
              </>
            ) : (
              <>
                You rejected the schema-consistent items that were not there, which
                is harder than it sounds. Note that the reconstruction is still
                missing low-prominence detail — the pen was in the scene.
              </>
            )}
          </p>

          <button type="button" onClick={begin} className="btn mt-3 w-full">
            Run again
          </button>
        </>
      ) : (
        phase === 'ready' && (
          <button type="button" onClick={begin} className="btn btn-primary w-full">
            Show the scene
          </button>
        )
      )}

      <p className="mt-3 text-[10.5px] leading-relaxed text-bone-faint">
        The four categories are a <strong>deliberate simplification</strong>. Real
        retrieval is graded and continuous across that whole range, and the
        boundary between &ldquo;weakly remembered&rdquo; and &ldquo;plausibly
        inferred&rdquo; is not sharp — in your brain or in this model.
      </p>
    </div>
  );
}
